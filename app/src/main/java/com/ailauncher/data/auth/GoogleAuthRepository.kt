private val Context.profileDataStore: DataStore<Preferences> by preferencesDataStore(name = "user_profile")

/**
 * Google Sign-In through the Android Credential Manager API (`GetGoogleIdOption`), optionally
 * linked to Firebase Auth for the encrypted cloud backup. All AI inference stays on-device either
 * way, and "Continue offline" (guest mode) never requires the network.
 *
 * Configuration (see README):
 *  * `google.web.client.id` in local.properties -> BuildConfig.GOOGLE_WEB_CLIENT_ID, or the
 *    `default_web_client_id` string generated from google-services.json;
 *  * app/google-services.json enables Firebase.
 */
@Singleton
class GoogleAuthRepository @Inject constructor(
    @ApplicationContext private val context: Context,
    @ApplicationScope private val scope: CoroutineScope,
) : AuthRepository {

    private val credentialManager = CredentialManager.create(context)
    private val store = context.profileDataStore

    private val _profile = MutableStateFlow<UserProfile?>(null)
    override val profile: StateFlow<UserProfile?> = _profile.asStateFlow()

    private val webClientId: String? by lazy {
        // The Google Play build ships without accounts or cloud backup.
        if (!BuildConfig.CLOUD_FEATURES) return@lazy null
        BuildConfig.GOOGLE_WEB_CLIENT_ID.takeIf { it.isNotBlank() } ?: run {
            // Generated by the google-services plugin when an OAuth web client exists.
            @Suppress("DiscouragedApi")
            val id = context.resources.getIdentifier("default_web_client_id", "string", context.packageName)
            if (id != 0) context.getString(id).takeIf { it.isNotBlank() } else null
        }
    }

    private val firebaseAvailable: Boolean by lazy {
        BuildConfig.CLOUD_FEATURES && BuildConfig.FIREBASE_CONFIGURED && runCatching { FirebaseApp.getApps(context).isNotEmpty() }.getOrDefault(false)
    }

    override val isGoogleSignInConfigured: Boolean get() = webClientId != null

    override val isCloudBackupAvailable: Boolean
        get() = firebaseAvailable && _profile.value?.firebaseLinked == true

    init {
        scope.launch {
            store.data.catch { if (it is IOException) emit(emptyPreferences()) else throw it }
                .collect { _profile.value = it.toProfile() }
        }
    }

    /**
     * Shows the Credential Manager bottom sheet. Previously authorised accounts are offered first
     * (and auto-selected when there is exactly one); otherwise all Google accounts are listed.
     * Requires an Activity context for the system UI.
     */
    suspend fun signIn(activity: Activity): Result<UserProfile> {
        val clientId = webClientId
            ?: return Result.failure(IllegalStateException("Google Sign-In is not configured for this build."))
        return try {
            val credential = try {
                requestCredential(activity, clientId, authorizedOnly = true)
            } catch (_: NoCredentialException) {
                requestCredential(activity, clientId, authorizedOnly = false)
            }
            val google = parseGoogleCredential(credential)
            val email: String? = google.email
            val stableId: String? = google.uniqueId
            var profile = UserProfile(
                uid = stableId?.takeIf { it.isNotBlank() } ?: email.orEmpty(),
                displayName = google.displayName?.takeIf { it.isNotBlank() } ?: email.orEmpty(),
                email = email,
                photoUrl = google.profilePictureUri?.toString(),
                isGuest = false,
                firebaseLinked = false,
            )
            if (firebaseAvailable) {
                try {
                    val result = FirebaseAuth.getInstance()
                        .signInWithCredential(GoogleAuthProvider.getCredential(google.idToken, null))
                        .await()
                    result.user?.let { user ->
                        profile = profile.copy(
                            uid = user.uid,
                            displayName = user.displayName ?: profile.displayName,
                            photoUrl = user.photoUrl?.toString() ?: profile.photoUrl,
                            firebaseLinked = true,
                        )
                    }
                } catch (e: CancellationException) {
                    throw e
                } catch (e: Exception) {
                    // Signed in with Google but not Firebase (e.g. offline): cloud backup stays off.
                    Log.w(TAG, "Firebase sign-in failed", e)
                }
            }
            save(profile)
            Result.success(profile)
        } catch (e: GetCredentialCancellationException) {
            Result.failure(SignInCancelledException())
        } catch (e: NoCredentialException) {
            Result.failure(IllegalStateException("No Google account is available on this device.", e))
        } catch (e: GetCredentialException) {
            Result.failure(IllegalStateException(e.message ?: "Google Sign-In failed.", e))
        } catch (e: GoogleIdTokenParsingException) {
            Result.failure(IllegalStateException("Google returned an invalid credential.", e))
        }
    }

    private suspend fun requestCredential(activity: Activity, clientId: String, authorizedOnly: Boolean): Credential {
        val option = GetGoogleIdOption.Builder()
            .setServerClientId(clientId)
            .setFilterByAuthorizedAccounts(authorizedOnly)
            .setAutoSelectEnabled(authorizedOnly)
            .setNonce(newNonce())
            .build()
        val request = GetCredentialRequest.Builder().addCredentialOption(option).build()
        return credentialManager.getCredential(activity, request).credential
    }

    private fun parseGoogleCredential(credential: Credential): GoogleIdTokenCredential {
        if (credential is CustomCredential && credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
            return GoogleIdTokenCredential.createFrom(credential.data)
        }
        throw IllegalStateException("Unexpected credential type: ${credential.type}")
    }

    override suspend fun continueAsGuest() = save(UserProfile.Guest)

    override suspend fun signOut() {
        runCatching { credentialManager.clearCredentialState(ClearCredentialStateRequest()) }
        if (firebaseAvailable) runCatching { FirebaseAuth.getInstance().signOut() }
        save(UserProfile.Guest)
    }

    private suspend fun save(profile: UserProfile) {
        store.edit { prefs ->
            prefs[Keys.UID] = profile.uid
            prefs[Keys.NAME] = profile.displayName
            prefs[Keys.EMAIL] = profile.email.orEmpty()
            prefs[Keys.PHOTO] = profile.photoUrl.orEmpty()
            prefs[Keys.GUEST] = profile.isGuest
            prefs[Keys.FIREBASE] = profile.firebaseLinked
        }
    }

    private fun Preferences.toProfile(): UserProfile? {
        val uid = this[Keys.UID] ?: return null
        return UserProfile(
            uid = uid,
            displayName = this[Keys.NAME].orEmpty(),
            email = this[Keys.EMAIL]?.takeIf { it.isNotEmpty() },
            photoUrl = this[Keys.PHOTO]?.takeIf { it.isNotEmpty() },
            isGuest = this[Keys.GUEST] ?: true,
            firebaseLinked = this[Keys.FIREBASE] ?: false,
        )
    }

    private fun newNonce(): String {
        val bytes = ByteArray(16).also { SecureRandom().nextBytes(it) }
        return bytes.joinToString("") { "%02x".format(it) }
    }

    private object Keys {
        val UID = stringPreferencesKey("uid")
        val NAME = stringPreferencesKey("display_name")
        val EMAIL = stringPreferencesKey("email")
        val PHOTO = stringPreferencesKey("photo_url")
        val GUEST = booleanPreferencesKey("guest")
        val FIREBASE = booleanPreferencesKey("firebase_linked")
    }

    class SignInCancelledException : Exception("Sign-in was cancelled.")

    private companion object {
        const val TAG = "GoogleAuthRepository"
    }
}
